export function createFreshWorkspace(params: {
  slug: string;
  companyName: string;
  industry: string;
  billingEmail: string;
  setupDurationSeconds?: number | null;
}): Workspace {
  const now = new Date();
  const nowIso = now.toISOString();
  return {
    id: `ws_${crypto.randomUUID().slice(0, 8)}`,
    slug: params.slug,
    companyName: params.companyName.trim(),
    industry: params.industry.trim() || "Field Operations & Trades",
    timezone: "America/Chicago",
    createdAt: nowIso,
    updatedAt: nowIso,
    billing: {
      planId: "trial_smb",
      planName: "SMB Flat Plan (14-Day Trial)",
      monthlyPriceUsd: 29,
      seatLimit: 25,
      status: "trialing",
      cardBrand: null,
      cardLast4: null,
      billingEmail: params.billingEmail.trim(),
      setupCompletedAt: nowIso,
      setupDurationSeconds: params.setupDurationSeconds ?? 210,
      currentPeriodEnd: addDaysToIsoDate(toIsoDateString(now), 14),
      stripeCustomerId: null,
      stripeSubscriptionId: null,
    },
    integrations: readLiveIntegrationFlags(),
    employees: [],
    certifications: [],
    alertRules: DEFAULT_ALERT_RULES.map((r) => ({ ...r, channels: [...r.channels] })),
    alertDeliveries: [],
    smsMessages: [],
  };
}

